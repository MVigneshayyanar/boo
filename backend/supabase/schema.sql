-- Run this SQL in your Supabase Project -> SQL Editor

-- 1. Stores table (multi-store SaaS)
create table if not exists public.stores (
  id bigint generated by default as identity primary key,
  store_login_id text not null unique,
  password_hash text not null,
  store_hash text not null unique,
  name text not null,
  address text not null default '',
  gstin text not null default '',
  phone text not null default '',
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. Products table (scoped per store)
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  store_id bigint references public.stores(id) on delete cascade,
  name text not null,
  category text not null default 'Dress',
  type text not null,
  color text not null,
  price numeric(12, 2) not null default 0,
  price_visible boolean not null default true,
  is_available boolean not null default true,
  storage_location text not null default '',
  image_url text not null default '',
  description text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Add store_id if migrating from an existing products table
alter table public.products add column if not exists store_id bigint references public.stores(id) on delete cascade;

-- 3. Bookings table (scoped per store)
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  store_id bigint references public.stores(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  customer_name text not null,
  customer_phone text not null default '',
  function_date date not null,
  collection_date date not null,
  return_date date not null,
  base_price numeric(12, 2) not null,
  discount_type text not null default 'none',
  discount_value numeric(12, 2) not null default 0,
  discount_amount numeric(12, 2) not null default 0,
  final_price numeric(12, 2) not null,
  status text not null default 'Confirmed',
  notes text not null default '',
  created_at timestamptz not null default now()
);

-- Add store_id if migrating from an existing bookings table
alter table public.bookings add column if not exists store_id bigint references public.stores(id) on delete cascade;

create index if not exists idx_products_store on public.products (store_id);
create index if not exists idx_bookings_store_dates on public.bookings (store_id, return_date, status);
create index if not exists idx_bookings_product_dates on public.bookings (product_id, collection_date, return_date);

-- Disable RLS & grant API access for anon/authenticated
alter table public.stores disable row level security;
alter table public.products disable row level security;
alter table public.bookings disable row level security;

grant usage on schema public to anon, authenticated;
grant all on table public.stores, public.products, public.bookings to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Public Storage bucket for uploaded product images
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "Public read product images" on storage.objects;
create policy "Public read product images"
  on storage.objects for select
  using (bucket_id = 'product-images');

drop policy if exists "Public upload product images" on storage.objects;
create policy "Public upload product images"
  on storage.objects for insert
  with check (bucket_id = 'product-images');

-- Refresh PostgREST schema cache
notify pgrst, 'reload schema';
